def class_modifier_add(dataset_name: str) -> int:
    return _CLASS_OFFSET_ADD.get(dataset_name, 0)


_CLASS_OFFSET_MULTI: dict[str, float] = {
    "ECG200": 0.5,
    "FordA": 0.5,
    "FordB": 0.5,
    "Lightning2": 0.5,
    "Wafer": 0.5,
}


def class_modifier_multi(dataset_name: str) -> float:
    return _CLASS_OFFSET_MULTI.get(dataset_name, 1)


def class_offset(y: Any, dataset_name: str) -> Any:
    return (y + class_modifier_add(dataset_name)) * class_modifier_multi(dataset_name)
